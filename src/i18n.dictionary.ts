type DictionaryTable = Record<string, string>;
type ReplacementTable = Record<string, string>;

/**
 * Keep the Dictionary catalogue in one place while still giving every supported
 * language a complete, concrete table. The exact phrases below handle the prose
 * messages; the word replacements cover the compact labels and interpolated rows.
 */
const translatedTable = (replacements: ReplacementTable): DictionaryTable => {
  const entries = Object.entries(
    DICTIONARY_TRANSLATIONS.en as DictionaryTable,
  ).map(([key, value]) => {
    const replacement = replacements[value];
    if (replacement) return [key, replacement] as const;
    const translated = Object.entries(replacements)
      .sort(([left], [right]) => right.length - left.length)
      .reduce(
        (current, [source, target]) => current.split(source).join(target),
        value,
      );
    return [key, translated] as const;
  });
  return Object.fromEntries(entries);
};


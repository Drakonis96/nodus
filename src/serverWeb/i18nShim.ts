export function setActiveLang(language: AppLanguage): void {
  active = normalizeUiLanguage(language);
}
export function getActiveLang(): AppLanguage {
  return active;
}
export function resolveTranslation(
  language: unknown,
  source: string,
  tables: TranslationTables = DESKTOP_TABLES,
): string {
  const normalized = normalizeUiLanguage(language);
  if (normalized === "es") return source;
  return (
    SERVER_SETTINGS_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_FINAL_CHROME_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_PERSONAL_STATUS_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_ADVANCED_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_CONVERSATION_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_PERSONAL_EXTRA[normalized]?.[source] ??
    SERVER_WEB_PERSONAL_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_SETTINGS_ACTION_TRANSLATIONS[
      normalized as Exclude<AppLanguage, "es">
    ]?.[source] ??
    SERVER_WEB_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_VAULT_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_ACADEMIC_SHELL_TRANSLATIONS[normalized]?.[source] ??
    SERVER_WEB_ACADEMIC_TRANSLATIONS[normalized]?.[source] ??
    tables[normalized]?.[source] ??
    SERVER_TRANSLATIONS[normalized]?.[source] ??
    // English is the final safety net only after every catalogue for the
    // requested locale has had an opportunity to resolve the key. An English
    // table earlier in the chain masked valid translations from later tables.
    SERVER_SETTINGS_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_PERSONAL_STATUS_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_ADVANCED_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_CONVERSATION_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_PERSONAL_EXTRA.en?.[source] ??
    SERVER_WEB_PERSONAL_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_SETTINGS_ACTION_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_VAULT_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_ACADEMIC_SHELL_TRANSLATIONS.en?.[source] ??
    SERVER_WEB_ACADEMIC_TRANSLATIONS.en?.[source] ??
    tables.en?.[source] ??
    SERVER_TRANSLATIONS.en?.[source] ??
    source
  );
}
/**
 * The catalogues resolveTranslation() consults for the requested locale, in the
 * same order. Kept beside it so the two cannot drift: anything added to the
 * chain above belongs here too.
 */
const LOCALE_CATALOGUES: Partial<Record<string, Record<string, string>>>[] = [
  SERVER_SETTINGS_TRANSLATIONS,
  SERVER_WEB_FINAL_CHROME_TRANSLATIONS,
  SERVER_WEB_PERSONAL_STATUS_TRANSLATIONS,
  SERVER_WEB_ADVANCED_TRANSLATIONS,
  SERVER_WEB_CONVERSATION_TRANSLATIONS,
  SERVER_WEB_PERSONAL_EXTRA,
  SERVER_WEB_PERSONAL_TRANSLATIONS,
  SERVER_WEB_SETTINGS_ACTION_TRANSLATIONS,
  SERVER_WEB_TRANSLATIONS,
  SERVER_WEB_VAULT_TRANSLATIONS,
  SERVER_WEB_ACADEMIC_SHELL_TRANSLATIONS,
  SERVER_WEB_ACADEMIC_TRANSLATIONS,
  DESKTOP_TABLES,
  SERVER_TRANSLATIONS,
];

/**
 * Whether `language` can translate `source` from its own catalogues, i.e.
 * without falling through to the English safety net or, past that, to the
 * Spanish source itself. The i18n coverage gate reads this to check the
 * strings that live in src/serverWeb, which the desktop tables never hold.
 */
export function hasServerTranslation(
  language: AppLanguage,
  source: string,
): boolean {
  const normalized = normalizeUiLanguage(language);
  if (normalized === "es") return true;
  return LOCALE_CATALOGUES.some(
    (catalogue) => catalogue[normalized]?.[source] !== undefined,
  );
}

export function t(source: string): string {
  return resolveTranslation(active, source);
}
/** Translate the static text/labels in a server surface without touching
 * published record values. Unknown strings pass through unchanged. */
export function translateNode(node: ReactNode): ReactNode {
  if (typeof node === "string") return t(node);
  if (Array.isArray(node)) return node.map(translateNode);
  if (!isValidElement(node)) return node;
  const element = node as ReactElement<Record<string, unknown>>;
  const props: Record<string, unknown> = {};
  for (const key of ["placeholder", "title", "aria-label", "label"]) {
    if (typeof element.props[key] === "string")
      props[key] = t(element.props[key] as string);
  }
  if (element.props.children !== undefined)
    props.children = translateNode(element.props.children as ReactNode);
  return cloneElement(element, props);
}
export function tx(
  source: string,
  variables: Record<string, string | number>,
): string {
  return Object.entries(variables).reduce(
    (value, [key, replacement]) =>
      value.replaceAll(`{${key}}`, String(replacement)),
    t(source),
  );
}
export function tr(value: string): string {
  return t(value);
}
export function errorText(error: unknown): string {
  return t(error instanceof Error ? error.message : String(error));
}
export function pick<T>(
  values: Partial<Record<AppLanguage, T>> & { es: T; en: T },
): T {
  return values[active] ?? values.en;
}
export function notificationLine(
  value: unknown,
  fallback: string | undefined,
): string {
  return typeof value === "string" && value.trim()
    ? tr(value)
    : fallback
      ? t(fallback)
      : "";
}

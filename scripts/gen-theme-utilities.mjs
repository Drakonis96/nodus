/**
 * Generates the two theme stylesheets from `src/theme/themes.mjs`:
 *
 *   src/theme/tokens.generated.css     — ":root" fallback + per-theme --n-NNN / --a-NNN
 *   src/theme/utilities.generated.css  — every neutral / indigo Tailwind utility the
 *                                        app uses, remapped to var(--n-NNN) / var(--a-NNN),
 *                                        scoped under "html.theme-<id>" for each
 *                                        non-default theme
 *
 * The `default` theme gets NO utility block: it renders through raw Tailwind + the
 * hand-written `.light` rules in index.css and stays byte-identical to today.
 *
 * Run `npm run gen:theme` after editing themes.mjs. `scripts/test-theme-utilities-fresh.mjs`
 * fails CI if the committed files drift.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, SHADES } from '../src/theme/themes.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const OUT_TOKENS = path.join(ROOT, 'src/theme/tokens.generated.css');
const OUT_UTILS = path.join(ROOT, 'src/theme/utilities.generated.css');

// Tailwind's own scales — the `:root` fallback and the values the `default` theme
// keeps. Kept here so the generator is self-contained.
const TW_NEUTRAL = {
  50: '#fafafa', 100: '#f5f5f5', 200: '#e5e5e5', 300: '#d4d4d4', 400: '#a3a3a3',
  500: '#737373', 600: '#525252', 700: '#404040', 800: '#262626', 900: '#171717', 950: '#0a0a0a',
};
const TW_INDIGO = {
  50: '#eef2ff', 100: '#e0e7ff', 200: '#c7d2fe', 300: '#a5b4fc', 400: '#818cf8',
  500: '#6366f1', 600: '#4f46e5', 700: '#4338ca', 800: '#3730a3', 900: '#312e81', 950: '#1e1b4b',
};

const HEADER = '/* GENERATED by scripts/gen-theme-utilities.mjs — do not edit. Run `npm run gen:theme`. */\n';

// ── 1. Scan source for utility class tokens ──────────────────────────────────

const VARIANTS = 'dark|hover|focus|focus-visible|active|disabled|group-hover|group-focus|peer-focus|aria-selected|first|last|even|odd';
const PROPS = 'bg|text|border|ring|ring-offset|divide|from|to|via|fill|stroke|placeholder|caret|decoration|outline|accent';
const TOKEN_RE = new RegExp(
  `(?<![\\w-])((?:(?:${VARIANTS}):)*)(${PROPS})-(neutral|indigo)-(50|100|200|300|400|500|600|700|800|900|950)(?:/(\\d{1,3}))?(?![\\w-])`,
  'g',
);

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'theme' && dir === SRC) continue; // don't scan generated output
      out.push(...walk(full));
    } else if (/\.(tsx?|html)$/.test(entry.name)) {
      out.push(full);
    }
  }
  return out;
}

/** @type {Map<string, {variants:string[], prop:string, family:string, shade:number, alpha:number|null}>} */
const used = new Map();
const files = [...walk(SRC), path.join(ROOT, 'index.html'), path.join(ROOT, 'mascot.html')];
for (const file of files) {
  let text;
  try { text = readFileSync(file, 'utf8'); } catch { continue; }
  for (const m of text.matchAll(TOKEN_RE)) {
    const [, chain, prop, family, shade, alpha] = m;
    const key = `${chain}${prop}-${family}-${shade}${alpha ? '/' + alpha : ''}`;
    if (!used.has(key)) {
      used.set(key, {
        variants: chain ? chain.split(':').filter(Boolean) : [],
        prop, family, shade: Number(shade), alpha: alpha ? Number(alpha) : null,
      });
    }
  }
}

// Light dynamic-class insurance: any (prop, family) pair seen at least once gets its
// full opaque ramp emitted, so a future `` `bg-neutral-${n}` `` still resolves. Alpha
// permutations are only emitted when actually observed (there are none constructed
// dynamically today — checked with grep).
const seenPairs = new Set([...used.values()].map((u) => `${u.prop}|${u.family}`));
for (const pair of seenPairs) {
  const [prop, family] = pair.split('|');
  for (const shade of SHADES) {
    const key = `${prop}-${family}-${shade}`;
    if (!used.has(key)) used.set(key, { variants: [], prop, family, shade, alpha: null });
  }
}

// ── 2. Turn a parsed token into a CSS rule ───────────────────────────────────

const cssEscape = (cls) => cls.replace(/[:/]/g, (c) => '\\' + c);

/** CSS var reference (or color-mix for the alpha variants). */
function value(u) {
  const v = `var(--${u.family === 'neutral' ? 'n' : 'a'}-${u.shade})`;
  return u.alpha == null ? v : `color-mix(in srgb, ${v} ${u.alpha}%, transparent)`;
}

const ANCESTOR = { dark: '.dark', 'group-hover': ' .group:hover', 'group-focus': ' .group:focus', 'peer-focus': ' .peer:focus ~' };
const PSEUDO = {
  hover: ':hover', focus: ':focus', 'focus-visible': ':focus-visible', active: ':active',
  disabled: ':disabled', first: ':first-child', last: ':last-child', even: ':nth-child(even)', odd: ':nth-child(odd)',
  'aria-selected': '[aria-selected="true"]',
};

/** One or more `prop: value;` declarations for the utility's CSS property. */
function declarations(u) {
  const val = value(u);
  const transparent = u.alpha == null ? 'transparent' : value({ ...u, alpha: 0 });
  switch (u.prop) {
    case 'bg': return `background-color:${val};`;
    case 'text': return `color:${val};`;
    case 'border': return `border-color:${val};`;
    case 'divide': return `border-color:${val};`;
    case 'ring': return `--tw-ring-color:${val};`;
    case 'ring-offset': return `--tw-ring-offset-color:${val};`;
    case 'fill': return `fill:${val};`;
    case 'stroke': return `stroke:${val};`;
    case 'placeholder': return `color:${val};`;
    case 'caret': return `caret-color:${val};`;
    case 'decoration': return `text-decoration-color:${val};`;
    case 'outline': return `outline-color:${val};`;
    case 'accent': return `accent-color:${val};`;
    case 'from':
      return `--tw-gradient-from:${val} var(--tw-gradient-from-position);`
        + `--tw-gradient-to:${transparent} var(--tw-gradient-to-position);`
        + `--tw-gradient-stops:var(--tw-gradient-from),var(--tw-gradient-to);`;
    case 'to':
      return `--tw-gradient-to:${val} var(--tw-gradient-to-position);`;
    case 'via':
      return `--tw-gradient-to:${transparent} var(--tw-gradient-to-position);`
        + `--tw-gradient-stops:var(--tw-gradient-from),${val} var(--tw-gradient-via-position),var(--tw-gradient-to);`;
    default: return '';
  }
}

/** Full selector for a utility under one theme id. */
function selector(themeId, key, u) {
  let prefix = `html.theme-${themeId}`;
  let infix = ' ';
  const suffixes = [];
  for (const variant of u.variants) {
    if (variant === 'dark') prefix += '.dark';
    else if (ANCESTOR[variant]) infix = `${ANCESTOR[variant]} `;
    else if (PSEUDO[variant]) suffixes.push(PSEUDO[variant]);
  }
  let target = `.${cssEscape(key)}${suffixes.join('')}`;
  if (u.prop === 'divide') target += ' > :not([hidden]) ~ :not([hidden])';
  if (u.prop === 'placeholder') target += '::placeholder';
  return `${prefix}${infix}${target}`;
}

// ── 3. Emit utilities.generated.css ──────────────────────────────────────────

const sortedKeys = [...used.keys()].sort();
let utils = HEADER + '\n';
for (const theme of THEMES) {
  utils += `/* ── ${theme.label} (${theme.id}) ─────────────────────────────────── */\n`;
  const lines = [];
  for (const key of sortedKeys) {
    const u = used.get(key);
    const decl = declarations(u);
    if (decl) lines.push(`${selector(theme.id, key, u)} { ${decl} }`);
  }
  utils += lines.join('\n') + '\n\n';
}

// ── 4. Emit tokens.generated.css ─────────────────────────────────────────────

const varBlock = (selectorText, decls) => `${selectorText} {\n${decls.map((d) => `  ${d}`).join('\n')}\n}\n`;
const neutralDecls = (n) => SHADES.map((s) => `--n-${s}: ${n[s]};`);
const accentDecls = (a) => SHADES.map((s) => `--a-${s}: ${a[s]};`);

let tokens = HEADER + '\n/* Fallback = Tailwind neutral + indigo (the `default` theme keeps these). */\n';
tokens += varBlock(':root', [...neutralDecls(TW_NEUTRAL), ...accentDecls(TW_INDIGO)]) + '\n';
for (const theme of THEMES) {
  tokens += `/* ${theme.label} */\n`;
  // Neutral ramp is mode-independent; accent ramp is mode-split.
  tokens += varBlock(`html.theme-${theme.id}`, neutralDecls(theme.tokens.n));
  tokens += varBlock(`html.theme-${theme.id}.dark`, accentDecls(theme.tokens.a.dark));
  tokens += varBlock(`html.theme-${theme.id}.light`, accentDecls(theme.tokens.a.light));
  tokens += '\n';
}

// ── 5. Write ─────────────────────────────────────────────────────────────────

export function render() {
  return { tokens, utils };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('gen-theme-utilities.mjs')) {
  writeFileSync(OUT_TOKENS, tokens);
  writeFileSync(OUT_UTILS, utils);
  console.log(`gen:theme — ${THEMES.length} themes, ${sortedKeys.length} utilities`);
  console.log(`  ${path.relative(ROOT, OUT_TOKENS)}`);
  console.log(`  ${path.relative(ROOT, OUT_UTILS)}`);
}

/**
 * Generates the two theme stylesheets from `src/theme/themes.mjs`:
 *
 *   src/theme/tokens.generated.css     — ":root" fallback + per-theme --n-NNN / --a-NNN
 *   src/theme/utilities.generated.css  — every neutral / indigo Tailwind utility the
 *                                        app uses, remapped to var(--n-NNN) / var(--a-NNN),
 *                                        scoped under "html.theme-<id>" for each
 *                                        non-default theme
 *
 * The `default` theme gets NO utility block: it renders through raw Tailwind + the
 * hand-written `.light` rules in index.css and stays byte-identical to today.
 *
 * `npm run dev` and `npm run build` regenerate these automatically (see the
 * `gen-theme-utilities` Vite plugin in vite.config.ts), so editing themes.mjs is
 * enough day-to-day. `npm run gen:theme` remains as a manual entry point (e.g. to
 * regenerate without starting Vite). `scripts/test-theme-utilities-fresh.mjs` fails
 * CI if the committed files drift from themes.mjs.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, SHADES } from '../src/theme/themes.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const OUT_TOKENS = path.join(ROOT, 'src/theme/tokens.generated.css');
const OUT_UTILS = path.join(ROOT, 'src/theme/utilities.generated.css');

// Tailwind's own scales — the `:root` fallback and the values the `default` theme
// keeps. Kept here so the generator is self-contained.
const TW_NEUTRAL = {
  50: '#fafafa', 100: '#f5f5f5', 200: '#e5e5e5', 300: '#d4d4d4', 400: '#a3a3a3',
  500: '#737373', 600: '#525252', 700: '#404040', 800: '#262626', 900: '#171717', 950: '#0a0a0a',
};
const TW_INDIGO = {
  50: '#eef2ff', 100: '#e0e7ff', 200: '#c7d2fe', 300: '#a5b4fc', 400: '#818cf8',
  500: '#6366f1', 600: '#4f46e5', 700: '#4338ca', 800: '#3730a3', 900: '#312e81', 950: '#1e1b4b',
};

const HEADER = '/* GENERATED by scripts/gen-theme-utilities.mjs — do not edit. Run `npm run gen:theme`. */\n';

// ── 0. Learn light-mode neutral remaps from index.css ────────────────────────
//
// `.light .<neutral util> { … }` in index.css is ~200 hand-tuned rules that flip
// dark surfaces to pale and clamp neutral text to dark. A themed light mode has to
// make the SAME structural choice per utility (or a subtle border becomes a heavy
// line) — so we read those rules, take each target colour's luminance, and later
// map it to the nearest shade of the *theme's* ramp. Utilities `.light` leaves
// alone are left alone here too (Tailwind's own light value already fits).

function relLum(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => {
    const v = parseInt(hex.slice(1 + i, 3 + i), 16) / 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** Luminance of a CSS colour token (`#rrggbb`, `#rgb`, `rgb/rgba(...)`), or null. */
function lumOf(raw) {
  const s = raw.trim();
  let m = s.match(/^#([0-9a-f]{3}|[0-9a-f]{6})$/i);
  if (m) {
    const h = m[1].length === 3 ? m[1].replace(/./g, (c) => c + c) : m[1];
    return relLum('#' + h);
  }
  m = s.match(/^rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)/i);
  if (m) return relLum('#' + [m[1], m[2], m[3]].map((n) => Number(n).toString(16).padStart(2, '0')).join(''));
  return null;
}

const COLOR_DECL_RE = /(?:background-color|(?<![-\w])color|border-color|--tw-ring-color|--tw-ring-offset-color|fill|stroke|caret-color|text-decoration-color|outline-color)\s*:\s*([^;!]+)/;
const LIGHT_NEUTRAL_CLASS_RE = /^((?:(?:dark|hover|focus|focus-visible|active|group-hover|group-focus):)*)(bg|text|border|ring|ring-offset|divide|fill|stroke|caret|decoration|outline)-neutral-(50|100|200|300|400|500|600|700|800|900|950)(?:\/(\d{1,3}))?$/;

/** class string (as authored, unescaped) → target luminance from `.light`. */
const lightNeutralLum = new Map();
{
  const indexCss = readFileSync(path.join(ROOT, 'src/index.css'), 'utf8');
  for (const rule of indexCss.matchAll(/(\.light[^{}]*?)\s*\{([^{}]*)\}/gs)) {
    const decl = rule[2].match(COLOR_DECL_RE);
    if (!decl) continue;
    const lum = lumOf(decl[1]);
    if (lum == null) continue;
    for (let sel of rule[1].split(',')) {
      sel = sel.trim();
      if (!sel.startsWith('.light ')) continue; // ignore `.light.<vault>` compounds & non-light selectors
      const cls = sel.slice(7).trim()
        .replace(/::?[a-z-]+(\([^)]*\))?$/i, '') // trailing pseudo
        .replace(/^\./, '').replace(/\\/g, '');
      if (LIGHT_NEUTRAL_CLASS_RE.test(cls)) lightNeutralLum.set(cls, lum);
    }
  }
}

/** Nearest shade in `ramp` (shade→hex) to a target luminance. */
function nearestShade(ramp, targetLum) {
  let best = 500; let bestD = Infinity;
  for (const s of SHADES) {
    const d = Math.abs(relLum(ramp[s]) - targetLum);
    if (d < bestD) { bestD = d; best = s; }
  }
  return best;
}

// ── 1. Scan source for utility class tokens ──────────────────────────────────

const VARIANTS = 'dark|hover|focus|focus-visible|active|disabled|group-hover|group-focus|peer-focus|aria-selected|first|last|even|odd';
const PROPS = 'bg|text|border|ring|ring-offset|divide|from|to|via|fill|stroke|placeholder|caret|decoration|outline|accent';
const TOKEN_RE = new RegExp(
  `(?<![\\w-])((?:(?:${VARIANTS}):)*)(${PROPS})-(neutral|indigo)-(50|100|200|300|400|500|600|700|800|900|950)(?:/(\\d{1,3}))?(?![\\w-])`,
  'g',
);

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'theme' && dir === SRC) continue; // don't scan generated output
      out.push(...walk(full));
    } else if (/\.(tsx?|html)$/.test(entry.name)) {
      out.push(full);
    }
  }
  return out;
}

/** @type {Map<string, {variants:string[], prop:string, family:string, shade:number, alpha:number|null}>} */
const used = new Map();
const files = [...walk(SRC), path.join(ROOT, 'index.html'), path.join(ROOT, 'mascot.html')];
for (const file of files) {
  let text;
  try { text = readFileSync(file, 'utf8'); } catch { continue; }
  for (const m of text.matchAll(TOKEN_RE)) {
    const [, chain, prop, family, shade, alpha] = m;
    const key = `${chain}${prop}-${family}-${shade}${alpha ? '/' + alpha : ''}`;
    if (!used.has(key)) {
      used.set(key, {
        variants: chain ? chain.split(':').filter(Boolean) : [],
        prop, family, shade: Number(shade), alpha: alpha ? Number(alpha) : null,
      });
    }
  }
}

// Light dynamic-class insurance: any (prop, family) pair seen at least once gets its
// full opaque ramp emitted, so a future `` `bg-neutral-${n}` `` still resolves. Alpha
// permutations are only emitted when actually observed (there are none constructed
// dynamically today — checked with grep).
const seenPairs = new Set([...used.values()].map((u) => `${u.prop}|${u.family}`));
for (const pair of seenPairs) {
  const [prop, family] = pair.split('|');
  for (const shade of SHADES) {
    const key = `${prop}-${family}-${shade}`;
    if (!used.has(key)) used.set(key, { variants: [], prop, family, shade, alpha: null });
  }
}

// ── 2. Turn a parsed token into a CSS rule ───────────────────────────────────

const cssEscape = (cls) => cls.replace(/[:/]/g, (c) => '\\' + c);

/** CSS var reference (or color-mix for the alpha variants). */
function value(u) {
  const v = `var(--${u.family === 'neutral' ? 'n' : 'a'}-${u.shade})`;
  return u.alpha == null ? v : `color-mix(in srgb, ${v} ${u.alpha}%, transparent)`;
}

const ANCESTOR = { dark: '.dark', 'group-hover': ' .group:hover', 'group-focus': ' .group:focus', 'peer-focus': ' .peer:focus ~' };
const PSEUDO = {
  hover: ':hover', focus: ':focus', 'focus-visible': ':focus-visible', active: ':active',
  disabled: ':disabled', first: ':first-child', last: ':last-child', even: ':nth-child(even)', odd: ':nth-child(odd)',
  'aria-selected': '[aria-selected="true"]',
};

const mixA = (shade, alpha) => alpha == null
  ? `var(--a-${shade})`
  : `color-mix(in srgb, var(--a-${shade}) ${alpha}%, transparent)`;

/**
 * Light-mode declaration for an accent (indigo) utility.
 *
 * The app's `.light` rules don't just recolour indigo — they SHIFT it: dark indigo
 * borders/surfaces render pale, pale indigo text renders dark. A themed light mode
 * has to mirror that or subtle borders turn into heavy lines. This maps each accent
 * utility to a role-appropriate shade of the (contrast-tuned) light accent ramp.
 * Gradients are left to the default cascade. Returns `null` to skip.
 */
function lightAccentDeclarations(u) {
  const { prop, shade, alpha } = u;
  switch (prop) {
    case 'text': return `color:${mixA(700, alpha)};`;
    case 'decoration': return `text-decoration-color:${mixA(600, alpha)};`;
    case 'fill': return `fill:${mixA(600, alpha)};`;
    case 'stroke': return `stroke:${mixA(600, alpha)};`;
    case 'caret': return `caret-color:${mixA(600, alpha)};`;
    case 'accent': return `accent-color:${mixA(600, alpha)};`;
    case 'placeholder': return `color:${mixA(500, alpha)};`;
    case 'border': return `border-color:${mixA(200, alpha)};`;
    case 'divide': return `border-color:${mixA(200, alpha)};`;
    case 'ring': return `--tw-ring-color:${mixA(200, alpha)};`;
    case 'ring-offset': return `--tw-ring-offset-color:${mixA(200, alpha)};`;
    case 'outline': return `outline-color:${mixA(300, alpha)};`;
    case 'bg': {
      if (alpha != null) return `background-color:${mixA(500, alpha)};`;
      if (shade <= 300) return `background-color:var(--a-${shade});`;
      if (shade === 400) return `background-color:var(--a-300);`;
      return `background-color:var(--a-600);`; // solid accent badge/button
    }
    case 'from': case 'to': case 'via': return null;
    default: return null;
  }
}

/**
 * Dark-mode declaration for an accent (indigo) utility.
 *
 * The straight ramp is wrong here too: `--a-500..700` are darkened to clear
 * white-on-colour, so `text-indigo-500` (used bare, no `dark:` variant, e.g. the
 * icons in the Ideas panel) would vanish on a dark surface, and the low `bg`
 * shades the app uses as pale chips would flash near-white. Accent text/icons map
 * to a light shade; pale `bg` fills become a faint accent tint. Solid fills
 * (shade ≥ 500), tinted `bg`, borders and rings keep the straight shade.
 */
function darkAccentDeclarations(u) {
  const { prop, shade, alpha } = u;
  const textShade = shade <= 300 ? 300 : 400;
  switch (prop) {
    case 'text': return `color:${mixA(textShade, alpha)};`;
    case 'decoration': return `text-decoration-color:${mixA(300, alpha)};`;
    case 'fill': return `fill:${mixA(textShade, alpha)};`;
    case 'stroke': return `stroke:${mixA(textShade, alpha)};`;
    case 'caret': return `caret-color:${mixA(400, alpha)};`;
    case 'accent': return `accent-color:${mixA(400, alpha)};`;
    case 'placeholder': return `color:${mixA(400, alpha)};`;
    case 'outline': return `outline-color:${mixA(400, alpha)};`;
    case 'bg':
      if (alpha != null) return `background-color:${mixA(shade, alpha)};`;
      if (shade <= 400) return `background-color:color-mix(in srgb, var(--a-500) 16%, transparent);`;
      return `background-color:var(--a-${shade});`;
    case 'border': return `border-color:${mixA(shade, alpha)};`;
    case 'divide': return `border-color:${mixA(shade, alpha)};`;
    case 'ring': return `--tw-ring-color:${mixA(shade, alpha)};`;
    case 'ring-offset': return `--tw-ring-offset-color:${mixA(shade, alpha)};`;
    case 'from': case 'to': case 'via': return null;
    default: return null;
  }
}

/** One or more `prop: value;` declarations for the utility's CSS property.
 *  `key` is the authored class string; `theme` supplies the ramp hexes. */
function declarations(u, mode, key, theme) {
  if (u.family === 'indigo') return (mode === 'light' ? lightAccentDeclarations : darkAccentDeclarations)(u);
  let eff = u;
  if (mode === 'light' && u.family === 'neutral') {
    // Follow index.css's own `.light .<util>` decision: nearest theme shade to the
    // luminance it maps this utility to. Utilities `.light` leaves alone are left
    // alone (Tailwind's default light value already fits).
    const lum = lightNeutralLum.get(key);
    if (lum == null) return null;
    eff = { ...u, shade: nearestShade(theme.tokens.n, lum) };
  }
  const val = value(eff);
  const transparent = eff.alpha == null ? 'transparent' : value({ ...eff, alpha: 0 });
  switch (u.prop) {
    case 'bg': return `background-color:${val};`;
    case 'text': return `color:${val};`;
    case 'border': return `border-color:${val};`;
    case 'divide': return `border-color:${val};`;
    case 'ring': return `--tw-ring-color:${val};`;
    case 'ring-offset': return `--tw-ring-offset-color:${val};`;
    case 'fill': return `fill:${val};`;
    case 'stroke': return `stroke:${val};`;
    case 'placeholder': return `color:${val};`;
    case 'caret': return `caret-color:${val};`;
    case 'decoration': return `text-decoration-color:${val};`;
    case 'outline': return `outline-color:${val};`;
    case 'accent': return `accent-color:${val};`;
    case 'from':
      return `--tw-gradient-from:${val} var(--tw-gradient-from-position);`
        + `--tw-gradient-to:${transparent} var(--tw-gradient-to-position);`
        + `--tw-gradient-stops:var(--tw-gradient-from),var(--tw-gradient-to);`;
    case 'to':
      return `--tw-gradient-to:${val} var(--tw-gradient-to-position);`;
    case 'via':
      return `--tw-gradient-to:${transparent} var(--tw-gradient-to-position);`
        + `--tw-gradient-stops:var(--tw-gradient-from),${val} var(--tw-gradient-via-position),var(--tw-gradient-to);`;
    default: return '';
  }
}

/** Full selector for a utility under one theme id.
 *
 *  Neutral-family utilities are ALWAYS scoped to `.dark`: in light mode the app's
 *  own `.light .<util>` rules already remap `bg-neutral-900` etc. to pale surfaces,
 *  and a theme must not defeat that (a themed `--n-900` is a deep colour). Light
 *  themes therefore keep the default surface/text/border system and only recolour
 *  the accent. Accent-family utilities stay dual-mode; their token is mode-split. */
function selector(themeId, key, u, mode) {
  let prefix = `html.theme-${themeId}.${mode}`;
  let infix = ' ';
  const suffixes = [];
  for (const variant of u.variants) {
    if (variant === 'dark') { /* already mode-scoped */ }
    else if (ANCESTOR[variant]) infix = `${ANCESTOR[variant]} `;
    else if (PSEUDO[variant]) suffixes.push(PSEUDO[variant]);
  }
  let target = `.${cssEscape(key)}${suffixes.join('')}`;
  if (u.prop === 'divide') target += ' > :not([hidden]) ~ :not([hidden])';
  if (u.prop === 'placeholder') target += '::placeholder';
  return `${prefix}${infix}${target}`;
}

// ── 3. Emit utilities.generated.css ──────────────────────────────────────────

// `dark:`-variant utilities are emitted AFTER their bare counterparts so that, at
// equal specificity, `dark:hover:bg-neutral-900/55` wins over `hover:bg-neutral-50`
// in dark mode — i.e. the class the component author meant for dark mode wins,
// instead of the light-mode fallback flashing white / hiding text.
const sortedKeys = [...used.keys()].sort((a, b) => {
  const ad = used.get(a).variants.includes('dark') ? 1 : 0;
  const bd = used.get(b).variants.includes('dark') ? 1 : 0;
  return ad - bd || (a < b ? -1 : a > b ? 1 : 0);
});

/** Which modes a utility is emitted for. A `dark:`-variant utility only ever
 *  applies in dark mode; everything else is emitted for both (light mode mirrors
 *  the neutral ramp and role-shifts the accent). */
function modesFor(u) {
  return u.variants.includes('dark') ? ['dark'] : ['dark', 'light'];
}

let utils = HEADER + '\n';
for (const theme of THEMES) {
  utils += `/* ── ${theme.label} (${theme.id}) ─────────────────────────────────── */\n`;
  const lines = [];
  for (const key of sortedKeys) {
    const u = used.get(key);
    for (const mode of modesFor(u)) {
      const decl = declarations(u, mode, key, theme);
      if (decl) lines.push(`${selector(theme.id, key, u, mode)} { ${decl} }`);
    }
  }
  utils += lines.join('\n') + '\n\n';
}

// ── 4. Emit tokens.generated.css ─────────────────────────────────────────────

const varBlock = (selectorText, decls) => `${selectorText} {\n${decls.map((d) => `  ${d}`).join('\n')}\n}\n`;
const neutralDecls = (n) => SHADES.map((s) => `--n-${s}: ${n[s]};`);
const accentDecls = (a) => SHADES.map((s) => `--a-${s}: ${a[s]};`);

let tokens = HEADER + '\n/* Fallback = Tailwind neutral + indigo (the `default` theme keeps these). */\n';
tokens += varBlock(':root', [...neutralDecls(TW_NEUTRAL), ...accentDecls(TW_INDIGO)]) + '\n';
for (const theme of THEMES) {
  tokens += `/* ${theme.label} */\n`;
  // Neutral ramp is mode-independent; accent ramp is mode-split.
  tokens += varBlock(`html.theme-${theme.id}`, neutralDecls(theme.tokens.n));
  tokens += varBlock(`html.theme-${theme.id}.dark`, accentDecls(theme.tokens.a.dark));
  tokens += varBlock(`html.theme-${theme.id}.light`, accentDecls(theme.tokens.a.light));
  tokens += '\n';
}

// ── 5. Write ─────────────────────────────────────────────────────────────────

export function render() {
  return { tokens, utils };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('gen-theme-utilities.mjs')) {
  writeFileSync(OUT_TOKENS, tokens);
  writeFileSync(OUT_UTILS, utils);
  console.log(`gen:theme — ${THEMES.length} themes, ${sortedKeys.length} utilities`);
  console.log(`  ${path.relative(ROOT, OUT_TOKENS)}`);
  console.log(`  ${path.relative(ROOT, OUT_UTILS)}`);
}

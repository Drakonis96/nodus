// The two repositories agree, and a signed package from one installs into the other.
//
// Capability API v2 is a contract split across two repositories: Nodus enforces it and
// the marketplace publishes against it. Everything that can drift between them is a
// silent failure — a contract regenerated on one side only, a public key that stopped
// matching, a catalog naming a package that is not there — and none of it shows up in
// either repository's own tests.
//
// So this builds the real packages in a real marketplace checkout, signs them with a key
// generated for this run, and installs them through the application's own store: the same
// verification, the same extraction, the same registry, the same migrations, the same
// rollback. A production key is never involved; a release signed with one would not
// verify here, which is the point.
//
// It never passes by accident. Without a marketplace checkout it clones one, and if it
// cannot, it fails — there is no path through this file that reports success on a
// comparison it did not make.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { createHash, generateKeyPairSync, sign as signBytes } from 'node:crypto';
import { build } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'nodus-cross-repo-'));
const profile = path.join(scratch, 'profile');
fs.mkdirSync(profile, { recursive: true });

const step = name => console.log(`\n— ${name}`);
// `npm` is a shell script everywhere except Windows, where it is `npm.cmd` — and Node
// refuses to spawn a `.cmd` at all without going through a shell, so on Windows this one
// call does. The arguments are fixed here; nothing the marketplace provides reaches them.
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const npmOptions = process.platform === 'win32' ? { shell: true } : {};
const run = (command, args, options = {}) => execFileSync(command, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], ...options });

let failed = false;
const check = (name, assertion) => {
  try { assertion(); console.log(`  ok  ${name}`); }
  catch (error) { failed = true; console.error(`  FAIL ${name}\n      ${error instanceof Error ? error.message : String(error)}`); }
};

try {
  // ---------------------------------------------------------------- the checkout

  step('marketplace checkout');
  const marketplace = (() => {
    const given = process.env.NODUS_MARKETPLACE_DIR;
    if (given) {
      if (!fs.existsSync(path.join(given, 'plugins'))) throw new Error(`NODUS_MARKETPLACE_DIR is not a marketplace checkout: ${given}`);
      console.log(`  using ${given}`);
      return given;
    }
    // No path given: fetch one rather than skip. A cross-repository check that quietly
    // becomes a no-op is worse than one that is not run at all, because it reports a pass.
    const target = path.join(scratch, 'marketplace');
    const url = process.env.NODUS_MARKETPLACE_URL ?? 'https://github.com/NodusResearch/nodus-research-skill-marketplace.git';
    const branch = process.env.NODUS_MARKETPLACE_REF ?? 'main';
    console.log(`  cloning ${url} (${branch})`);
    run('git', ['clone', '--depth', '1', '--branch', branch, url, target]);
    return target;
  })();

  const marketplaceRead = file => fs.readFileSync(path.join(marketplace, file), 'utf8');

  // ---------------------------------------------------------------- the shared contract

  step('the published contract is the one this application enforces');
  const regenerated = path.join(scratch, 'contract-v2.mjs');
  await build({
    entryPoints: [path.join(root, 'packages/capability-api/src/index.ts')],
    outfile: regenerated, bundle: true, platform: 'node', format: 'esm', logLevel: 'silent',
    banner: { js: '// GENERATED by Nodus scripts/sync-skill-marketplace.mjs from @nodusresearch/capability-api; do not edit.' },
  });
  // Compared as content, not as bytes: a checkout on a machine configured for CRLF would
  // otherwise report the file as different from itself. What must not drift is what the
  // two repositories enforce.
  const sameText = value => value.replace(/\r\n/g, '\n');
  check('scripts/contract-v2.mjs matches @nodusresearch/capability-api', () => {
    assert.equal(
      sameText(marketplaceRead('scripts/contract-v2.mjs')),
      sameText(fs.readFileSync(regenerated, 'utf8')),
      'the marketplace validates against a different contract than the application enforces; regenerate it with scripts/sync-skill-marketplace.mjs',
    );
  });

  step('both repositories trust the same publishing keys');
  const applicationKeys = JSON.parse(fs.readFileSync(path.join(root, 'electron/capabilities/trustedKeys.json'), 'utf8')).keys;
  const marketplaceKeys = JSON.parse(marketplaceRead('trusted-keys.json')).keys;
  const fingerprint = keys => keys.map(key => `${key.keyId}:${createHash('sha256').update(key.publicKeyPem.replace(/\s+/g, '')).digest('hex').slice(0, 16)}${key.retiredAt ? ` retired ${key.retiredAt}` : ''}`).sort();
  check('the public keys are identical on both sides', () => {
    assert.deepEqual(fingerprint(marketplaceKeys), fingerprint(applicationKeys));
  });
  check('no private key is committed anywhere', () => {
    for (const file of ['trusted-keys.json']) {
      assert.ok(!marketplaceRead(file).includes('PRIVATE KEY'), `${file} contains a private key`);
    }
    assert.ok(!fs.readFileSync(path.join(root, 'electron/capabilities/trustedKeys.json'), 'utf8').includes('PRIVATE KEY'));
  });

  // ---------------------------------------------------------------- what it publishes

  step('the catalog describes what the repository holds');
  const sdk = await (async () => {
    const outfile = path.join(scratch, 'sdk.cjs');
    await build({ entryPoints: [path.join(root, 'packages/capability-api/src/index.ts')], outfile, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent' });
    return createRequire(import.meta.url)(outfile);
  })();

  const catalog = sdk.validateCapabilityCatalog(JSON.parse(marketplaceRead('catalog-v2.json')));
  const published = fs.readdirSync(path.join(marketplace, 'plugins'), { withFileTypes: true }).filter(entry => entry.isDirectory()).map(entry => entry.name).sort();
  check('every package in the repository is in the catalog, and nothing else is', () => {
    assert.deepEqual(catalog.plugins.map(entry => entry.id).sort(), published);
  });
  for (const entry of catalog.plugins) {
    const manifest = sdk.validatePluginManifestV2(JSON.parse(marketplaceRead(`plugins/${entry.id}/plugin.json`)));
    check(`${entry.id}: the catalog agrees with the package manifest`, () => {
      assert.equal(entry.version, manifest.version);
      assert.deepEqual(entry.targets, manifest.compatibility.targets);
      assert.deepEqual(entry.replaces, manifest.replacesSkills);
      assert.equal(entry.release.tag, `${entry.id}-v${manifest.version}`);
    });
    check(`${entry.id}: this build would accept the version the catalog offers`, () => {
      assert.ok(sdk.compareSemver('5.3.2', manifest.compatibility.minNodusVersion) >= 0);
    });
  }

  // ---------------------------------------------------------------- the real bytes

  step('building the packages the marketplace publishes');
  run(npm, ['ci'], { cwd: marketplace, stdio: 'inherit', ...npmOptions });
  run('node', ['scripts/validate-plugins.mjs'], { cwd: marketplace, stdio: 'inherit' });
  run('node', ['scripts/build-plugins.mjs'], { cwd: marketplace, stdio: 'inherit' });
  const first = fs.readFileSync(path.join(marketplace, 'build/index.json'), 'utf8');
  run('node', ['scripts/build-plugins.mjs'], { cwd: marketplace, stdio: 'inherit' });
  check('the build is reproducible', () => {
    assert.equal(fs.readFileSync(path.join(marketplace, 'build/index.json'), 'utf8'), first, 'a second build produced different bytes');
  });
  const index = JSON.parse(first);
  check('something was actually built', () => assert.ok(index.length > 0));

  // ---------------------------------------------------------------- signing, for this run only

  step('signing with a key generated for this run');
  const ephemeral = generateKeyPairSync('ed25519');
  // The key id follows the packages rather than being written here, so a rotation is
  // exercised by this check instead of breaking it.
  const keyId = sdk.validatePluginManifestV2(JSON.parse(marketplaceRead(`plugins/${published[0]}/plugin.json`))).publisher.keyId;
  const testKeys = { keys: [{ keyId, publicKeyPem: ephemeral.publicKey.export({ type: 'spki', format: 'pem' }).toString() }] };

  const releases = new Map();
  for (const entry of index) {
    const release = {
      schemaVersion: 1,
      plugin: entry.manifest.id,
      version: entry.manifest.version,
      publisher: { id: 'NodusResearch', keyId },
      createdAt: new Date().toISOString(),
      targets: [{ target: entry.target, asset: entry.asset, bytes: entry.bytes, sha256: entry.sha256 }],
    };
    const bytes = Buffer.from(`${JSON.stringify(release, null, 2)}\n`);
    releases.set(entry.manifest.id, {
      entry,
      releaseManifestBytes: bytes,
      signature: signBytes(null, bytes, ephemeral.privateKey),
      archive: fs.readFileSync(path.join(marketplace, 'build', entry.asset)),
    });
  }

  // The application's own store, with the ephemeral key in place of the committed one.
  const storeBundle = path.join(scratch, 'store.cjs');
  await build({
    stdin: {
      contents: `
        export * from './electron/capabilities/pluginStoreV2';
        export * from './electron/capabilities/registry';
        export * from './electron/capabilities/migration';
      `,
      resolveDir: root, loader: 'ts',
    },
    outfile: storeBundle, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent',
    plugins: [{
      name: 'cross-repo-environment',
      setup(api) {
        api.onResolve({ filter: /^electron$/ }, () => ({ path: 'electron', namespace: 'mock' }));
        api.onLoad({ filter: /.*/, namespace: 'mock' }, () => ({
          contents: `export const app={getPath:()=>${JSON.stringify(profile)},getVersion:()=>"5.3.2",isPackaged:false,getAppPath:()=>${JSON.stringify(scratch)}};`
            + 'export const safeStorage={isEncryptionAvailable:()=>true,encryptString:v=>Buffer.from(v),decryptString:v=>v.toString("utf8")};',
          loader: 'js',
        }));
        api.onResolve({ filter: /trustedKeys\.json$/ }, () => ({ path: 'keys', namespace: 'keys' }));
        api.onLoad({ filter: /.*/, namespace: 'keys' }, () => ({ contents: JSON.stringify(testKeys), loader: 'json' }));
        api.onResolve({ filter: /^@shared\// }, ({ path: value }) => ({ path: path.join(root, 'shared', `${value.slice(8)}.ts`) }));
      },
    }],
  });
  const store = createRequire(import.meta.url)(storeBundle);
  store.initializeCapabilityPluginStore();

  step('installing each package the way a user would');
  const source = { id: 'nodusresearch/nodus-research-skill-marketplace', path: 'plugins', commit: 'f'.repeat(40) };
  const target = `${process.platform}-${process.arch}`;
  for (const [id, release] of releases) {
    if (release.entry.target !== target && release.entry.target !== 'any') continue;
    // The refusals come first, against a store with nothing installed: once a version is
    // installed, a changed archive is refused for being a republished version rather than
    // for failing its release digest, which is correct and is not what is being shown here.
    check(`${id}: an archive that does not match its signed manifest is refused`, () => {
      const broken = Buffer.from(release.archive);
      broken[broken.length - 20] ^= 0xff;
      assert.throws(() => store.installVerifiedPlugin({ ...release, archive: broken, source }, { approvePermissions: true }), /digest|size/i);
      assert.equal(store.readPluginStateV2(id), null, 'a refused install left something behind');
    });

    check(`${id}: a release signed by someone else is refused`, () => {
      const impostor = generateKeyPairSync('ed25519');
      assert.throws(
        () => store.installVerifiedPlugin({ ...release, signature: signBytes(null, release.releaseManifestBytes, impostor.privateKey), source }, { approvePermissions: true }),
        /signature|verif/i,
      );
      assert.equal(store.readPluginStateV2(id), null);
    });

    check(`${id}: a signed release installs`, () => {
      const outcome = store.installVerifiedPlugin({ ...release, source }, { approvePermissions: true });
      assert.equal(outcome.activated, true, `${id} was staged but not activated`);
      assert.equal(outcome.state.trust.verified, true);
      assert.equal(outcome.state.active.version, release.entry.manifest.version);
    });

    check(`${id}: the same version republished over different bytes is refused`, () => {
      const rebuilt = Buffer.from(release.archive);
      rebuilt[rebuilt.length - 20] ^= 0xff;
      const manifest = JSON.parse(release.releaseManifestBytes.toString('utf8'));
      manifest.targets[0].sha256 = createHash('sha256').update(rebuilt).digest('hex');
      manifest.targets[0].bytes = rebuilt.byteLength;
      const bytes = Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`);
      // Correctly signed, and still a lie: this version already means something here.
      assert.throws(
        () => store.installVerifiedPlugin({ archive: rebuilt, releaseManifestBytes: bytes, signature: signBytes(null, bytes, ephemeral.privateKey), source }, { approvePermissions: true }),
        /published with different content/i,
      );
    });
  }

  step('the registry announces what was installed, once it has migrated');
  const installed = store.listInstalledPluginsV2();
  check('every package for this platform is installed', () => {
    const expected = [...releases.values()].filter(release => release.entry.target === target || release.entry.target === 'any').map(release => release.entry.manifest.id).sort();
    assert.deepEqual(installed.map(state => state.id).sort(), expected);
  });
  for (const state of installed) {
    const declared = sdk.validatePluginManifestV2(JSON.parse(marketplaceRead(`plugins/${state.id}/plugin.json`))).migrations.length;
    check(`${state.id}: waits for its ${declared} migration(s) before being announced`, () => {
      const registry = store.rebuildCapabilityRegistry();
      const provider = [...registry.providers.values()].find(entry => entry.plugin?.id === state.id);
      if (declared > state.dataVersion) {
        assert.equal(provider, undefined, 'announced before its data was migrated');
        assert.ok(registry.problems.some(problem => problem.pluginId === state.id), 'and says why it is not');
      } else {
        assert.ok(provider, 'not announced although it has nothing left to migrate');
      }
    });
    store.recordPluginDataVersion(state.id, declared);
  }
  const settled = store.rebuildCapabilityRegistry();
  check('with the migrations recorded, every capability is available', () => {
    assert.deepEqual(settled.problems, []);
    for (const state of installed) {
      assert.ok([...settled.providers.values()].some(provider => provider.plugin?.id === state.id), `${state.id} did not register`);
    }
  });
  check('the three reserved capabilities are provided by packages, not by the core', () => {
    for (const id of ['nodus:chemistry', 'nodus:legal', 'nodus:genomics']) {
      const provider = settled.providers.get(id);
      if (provider) assert.equal(provider.source, 'plugin', `${id} is provided by the core`);
    }
    assert.equal(settled.providers.get('nodus:svg').source, 'core', 'SVG left the core');
    assert.equal(settled.providers.get('nodus:image').source, 'core', 'image generation left the core');
  });

  step('rollback and removal');
  for (const state of installed) {
    check(`${state.id}: removing it takes the capability with it`, () => {
      store.removePluginV2(state.id);
      const after = store.rebuildCapabilityRegistry();
      assert.ok(![...after.providers.values()].some(provider => provider.plugin?.id === state.id));
      assert.ok(store.pluginTombstone(state.id), 'and leaves a tombstone so a reinstall finds its place');
    });
  }

  // ---------------------------------------------------------------- offline bootstrap

  step('the offline bootstrap carries what the migration needs');
  const bootstrap = JSON.parse(fs.readFileSync(path.join(root, 'electron/capabilities/bootstrap.json'), 'utf8'));
  check('every package the migration may need is pinned for bundling', () => {
    const needed = store.MIGRATION_MAP.map(entry => entry.pluginId).sort();
    assert.deepEqual(bootstrap.packages.map(entry => entry.id).sort(), needed);
  });
  for (const entry of bootstrap.packages) {
    check(`${entry.id}: the pinned version is the one the marketplace publishes`, () => {
      const manifest = JSON.parse(marketplaceRead(`plugins/${entry.id}/plugin.json`));
      assert.equal(entry.version, manifest.version, 'the bootstrap pins a version the marketplace does not publish');
    });
    check(`${entry.id}: a pinned release is fully described`, () => {
      if (!entry.releaseUrl) {
        assert.deepEqual(entry.assets, [], 'a package with no release must pin no assets');
        return;
      }
      assert.match(entry.releaseUrl, /^https:\/\/github\.com\/NodusResearch\//);
      assert.ok(entry.assets.length, 'a pinned release must name its assets');
      for (const asset of entry.assets) {
        assert.match(asset.sha256, /^[a-f0-9]{64}$/);
        assert.ok(Number.isInteger(asset.bytes) && asset.bytes > 0);
      }
    });
  }

  console.log(failed ? '\nCROSS-REPO FAIL' : '\nCROSS-REPO PASS: shared contract, identical keys, catalog, reproducible build, signature, install, migration gate, rollback, bootstrap.');
} finally {
  fs.rmSync(scratch, { recursive: true, force: true });
}

process.exit(failed ? 1 : 0);

// Textbook-scheme reactions (tools/scheme-scan): the index has the ORD format, its "tb-…" ids
// resolve to book, page and conditions through records.json, and the route report and the
// pre-answer evidence cite them. Checks the formatting, the id handling (ORD lookups never accept
// tb- ids, textbook lookups do), the directory resolver and the page links.
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = await mkdtemp(path.join(os.tmpdir(), 'nodus-textbook-schemes-'));
test.after(() => rm(tmp, { recursive: true, force: true }));

async function bundle(entry, name, plugins = []) {
  const outfile = path.join(tmp, name);
  await build({ entryPoints: [path.join(root, entry)], outfile, bundle: true, format: 'esm', platform: 'node', logLevel: 'silent', alias: { '@shared': path.join(root, 'shared') }, plugins });
  return import(pathToFileURL(outfile).href);
}

const shared = await bundle('shared/textbookSchemes.ts', 'shared-textbook.mjs');
const inspection = await bundle('shared/moleculeInspection.ts', 'inspection.mjs');

const ID_A = `tb-${'a'.repeat(32)}`;
const ID_B = `tb-${'b'.repeat(32)}`;
const ID_W = `tb-${'c'.repeat(32)}`;
const RECORDS = {
  [ID_A]: { key: 'k1', book: 'Carey B', nodusId: 'U2YJMYA7', page: 37, kind: 'crop', reagents: 'Ph3CLi, DME', yield: '100% : 0%', status: 'confirmed', reaction: 'CC(C)C1CCCCC1=O>>CC(C)C1=C([O-])CCCC1' },
  [ID_B]: { key: 'k1', book: 'Clayden', nodusId: 'Q5V62WM4', page: 590, kind: 'crop', reagents: 'LDA, THF, −78 °C', yield: null, status: 'repaired', reaction: 'CC(C)C1CCCCC1=O>>CC(C)C1CCCC=C1[O-]' },
  [ID_W]: { key: 'k2', book: 'Warren (Disconnection Approach)', nodusId: 'I6L63XQX', page: 21, kind: 'image', reagents: 'MeI', yield: null, status: 'confirmed', reaction: 'CC(=O)CC>>CC(=O)C(C)C' },
};
const cite = (ids) => ids.filter((id) => RECORDS[id]).map((id) => shared.textbookCitation(id, RECORDS[id], id === ID_A ? 'nodus://passage/carey%2337' : null));

test('a citation says book, page, conditions and yield, and whether a structure was repaired', () => {
  const [a, b, w] = cite([ID_A, ID_B, ID_W]);
  assert.equal(shared.formatTextbookCitation(a), '[*Carey B*, p. 37](nodus://passage/carey%2337) · conditions: Ph3CLi, DME · yield 100% : 0%');
  assert.equal(shared.formatTextbookCitation(b), '*Clayden*, p. 590 · conditions: LDA, THF, −78 °C (a structure was corrected from its name and formula)');
  assert.equal(shared.formatTextbookCitation(w), '*Warren (Disconnection Approach)*, chapter 21 · conditions: MeI', 'an EPUB image is cited by chapter, unlinked');
});

test('conditions are clipped and whitespace is collapsed', () => {
  const long = shared.textbookCitation(ID_A, { ...RECORDS[ID_A], reagents: `1. ${'LiAlH4 '.repeat(60)}\n2. H3O+` });
  assert.ok(long.reagents.length <= 160 && long.reagents.endsWith('…'));
});

test('ORD lookups keep refusing tb- ids; textbook lookups accept them', () => {
  const data = { reactions: [{ input: 'a>>b', count: 2, samples: [ID_A, 'ord-' + '0'.repeat(32), 'nonsense'] }], products: [], similar: [] };
  assert.deepEqual(inspection.normalizeReactionPrecedent(data).reactions[0].samples, ['ord-' + '0'.repeat(32)]);
  assert.deepEqual(inspection.normalizeReactionPrecedent(data, shared.TEXTBOOK_ID).reactions[0].samples, [ID_A]);
});

test('the route section cites exact matches and names the closest reaction otherwise', () => {
  const precedent = inspection.normalizeReactionPrecedent({
    reactions: [
      { input: 'CC(C)C1CCCCC1=O>>CC(C)C1=C([O-])CCCC1', count: 2, samples: [ID_A, ID_B] },
      { input: 'CCO>>CC=O', count: 0 },
      { input: 'C>>CO', count: 0 },
    ],
    products: [{ input: 'CC(C)C1=C([O-])CCCC1', count: 2, keys: ['k1'] }],
    similar: [
      { input: 'CCO>>CC=O', neighbors: [{ key: 'k3', distance: 9, count: 1, similarity: 0.82, reaction: 'CCCO>>CCC=O' }] },
      { input: 'C>>CO', neighbors: [{ key: 'k4', distance: 40, count: 1, similarity: 0.21, reaction: 'CC>>CCO' }] },
    ],
  }, shared.TEXTBOOK_ID);
  const queries = [{ step: 0, query: 'CC(C)C1CCCCC1=O>>CC(C)C1=C([O-])CCCC1' }, { step: 2, query: 'CCO>>CC=O' }, { step: 3, query: 'C>>CO' }];
  const text = shared.formatTextbookPrecedents(precedent, cite, { queries, target: { smiles: 'CC(C)C1=C([O-])CCCC1', name: 'the kinetic enolate' } });
  assert.match(text, /^\n### Known reactions \(textbook schemes\)\nThis block is generated by the application, not by the model/);
  assert.match(text, /Target: \*\*the kinetic enolate\*\* — `CC\(C\)C1=C\(\[O-\]\)CCCC1` · made in 2 textbook scheme\(s\)\./);
  assert.match(text, /\*\*Step 1\*\* — ✔ in 2 textbook scheme\(s\):\n- \[\*Carey B\*, p\. 37\]\(nodus:\/\/passage\/carey%2337\) · conditions: Ph3CLi, DME · yield 100% : 0%\n- \*Clayden\*, p\. 590/);
  assert.match(text, /\*\*Step 3\*\* — closest textbook reaction: 82% similar — same transformation, different substrate\. `CCCO>>CCC=O`/);
  assert.doesNotMatch(text, /Step 4/, 'a loosely related neighbour is not worth a line');
  assert.match(text, /checked against the name and formula/);
});

test('nothing to say: no section', () => {
  const precedent = inspection.normalizeReactionPrecedent({ reactions: [{ input: 'C>>CO', count: 0 }], products: [{ input: 'CO', count: 0 }], similar: [] }, shared.TEXTBOOK_ID);
  assert.equal(shared.formatTextbookPrecedents(precedent, cite), '');
});

test('textbook preparations: made-by reactions with resolvable citations only, capped', () => {
  const data = { disconnections: [
    { input: 'X', target: 'CC(C)C1=C([O-])CCCC1', madeBy: { count: 2, reactions: [
      { key: 'k1', count: 2, samples: [ID_A, ID_B, ID_W], reaction: 'CC(C)C1CCCCC1=O>>CC(C)C1=C([O-])CCCC1' },
      { key: 'k9', count: 1, samples: [`tb-${'f'.repeat(32)}`], reaction: 'CC>>CC' },
      { key: 'k8', count: 1, samples: [ID_A], reaction: 'not a reaction' },
    ] }, proposals: [{ precursors: 'ignored', classes: [], recorded: 0 }] },
    { input: 'Y', target: 'CCO', madeBy: null, proposals: [] },
  ] };
  const preps = shared.textbookPreparations(data, cite);
  assert.equal(preps.length, 1);
  assert.equal(preps[0].reactions.length, 1, 'unknown ids and malformed reactions are dropped');
  assert.equal(preps[0].reactions[0].citations.length, 2, 'two citations per reaction');
  assert.deepEqual(shared.textbookPreparations({}, cite), []);
});

test('the directory resolver needs a complete textbook-scheme index; citations link to the page passage', async () => {
  const dir = path.join(tmp, 'index');
  await mkdir(dir, { recursive: true });
  const db = {
    prepare: (sql) => ({
      get: (...args) => {
        if (sql.includes('FROM works')) return args[0] === 'U2YJMYA7' ? { nodus_id: 'carey-b' } : undefined;
        if (sql.includes('FROM passages')) return args[0] === 'carey-b' && args[1] >= 30 ? { passage_id: 'carey-b#36' } : undefined;
        return undefined;
      },
    }),
  };
  globalThis.__textbookDb = db;
  const electron = await bundle('electron/ai/textbookSchemes.ts', 'electron-textbook.mjs', [{
    name: 'stubs',
    setup(b) {
      const stubs = {
        electron: `export const app = { getPath: () => ${JSON.stringify(path.join(tmp, 'userData'))} };`,
        '../db/database': 'export const getDb = () => globalThis.__textbookDb;',
      };
      b.onResolve({ filter: /^(electron|\.\.\/db\/database)$/ }, (args) => ({ path: args.path, namespace: 'stub' }));
      b.onLoad({ filter: /.*/, namespace: 'stub' }, (args) => ({ contents: stubs[args.path], loader: 'js' }));
    },
  }]);
  process.env.NODUS_SCHEME_INDEX_DIR = dir;
  try {
    assert.equal(electron.textbookSchemeDirectory(), null, 'an empty directory is not an index');
    for (const name of ['exact.tsv.zst', 'products.tsv.zst', 'reaction-smiles.tsv.zst', 'molecules.tsv.zst', 'reactions.faiss.zst', 'reaction-keys.txt.zst']) await writeFile(path.join(dir, name), '');
    await writeFile(path.join(dir, 'records.json'), JSON.stringify({ ...RECORDS, 'not-an-id': RECORDS[ID_A] }));
    await writeFile(path.join(dir, 'manifest.json'), JSON.stringify({ source: 'open-reaction-database/ord-data' }));
    assert.equal(electron.textbookSchemeDirectory(), null, 'an ORD index is not a textbook index');
    await writeFile(path.join(dir, 'manifest.json'), JSON.stringify({ source: 'nodus.textbook-schemes' }));
    assert.equal(electron.textbookSchemeDirectory(), dir);
    const [a, b, w] = electron.textbookCitations([ID_A, 'not-an-id', ID_B, ID_W]);
    assert.equal(a.link, 'nodus://passage/carey-b%2336', 'the passage covering the page');
    assert.equal(b.book, 'Clayden');
    assert.equal(b.link, null, 'a book without text in the library is cited unlinked');
    assert.equal(w.link, null, 'an EPUB image has no page link');
    globalThis.__textbookDb = { prepare: () => { throw new Error('no database'); } };
    assert.equal(electron.textbookCitations([ID_A])[0].link, null, 'a database failure only drops the link');
  } finally {
    delete process.env.NODUS_SCHEME_INDEX_DIR;
  }
});

import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(repoRoot, relative), 'utf8');

/** The hero art is generated from the app's components; these assertions guard the
 *  contract around that file, not the hundreds of numbers inside it. */
test('the home hero draws Nodi from the app components instead of an illustration', () => {
  const home = read('site/index.html');
  assert.match(home, /<!-- generated:what-nodi:start -->[\s\S]*<!-- generated:what-nodi:end -->/, 'the generated figure block is in place');
  const figure = home.slice(home.indexOf('<!-- generated:what-nodi:start -->'), home.indexOf('<!-- generated:what-nodi:end -->'));

  assert.match(figure, /<figure class="what-nodi">/, 'the figure keeps the class the section styles');
  assert.doesNotMatch(figure, /<img\b/, 'the hero no longer ships a raster illustration');
  assert.match(figure, /<svg class="what-nodi-figure"[^>]*role="img"[^>]*aria-label="[^"]{20,}"/, 'the figure describes itself to assistive tech');
  assert.match(figure, /<g class="nodi-orb"/, 'the orb is the app component');
  assert.match(figure, /<svg class="nodi-svg"[^>]*data-state="waving"/, 'the character waves, as the illustration had it');
  assert.match(figure, /class="what-nodi-peek" mask="url\(#wn-peek\)"/, 'the character is masked by the sphere it hides behind');
  assert.ok(figure.indexOf('class="nodi-orb"') < figure.indexOf('class="what-nodi-peek"'), 'the orb paints first, so the character cannot cover it');

  assert.match(home, /<link rel="stylesheet" href="assets\/css\/what-nodi\.css\?v=\d+[a-z]?"/, 'the page loads the component stylesheet the figure needs');
});

test('the component stylesheet is generated, and carries the components verbatim', () => {
  const css = read('site/assets/css/what-nodi.css');
  assert.match(css, /Generated by\s*\n?\s*\*? ?scripts\/build-what-nodi\.mjs/, 'the file says where it comes from');
  assert.match(css, /Do not edit by hand/, 'the file says not to edit it');
  for (const component of ['nodiOrb.css', 'nodi.css']) {
    assert.ok(css.includes(read(`src/components/nodi/${component}`).trimEnd()), `${component} is copied whole, so the site and the app cannot drift`);
  }
  assert.match(read('package.json'), /"site:what-nodi": "node scripts\/build-what-nodi\.mjs"/, 'the generator is reachable from npm');
});

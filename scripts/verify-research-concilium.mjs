import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:5198/visual-tests/research-assistant-harness.html?lang=en&view=embedded');
  const trigger = page.getByRole('button', { name: 'Concilium', exact: true });
  await trigger.click();
  const panel = page.getByTestId('concilium-panel');
  // The shared header balloon, like Context, Sources, System prompt and Skills.
  assert.equal(await panel.getAttribute('role'), 'dialog');
  assert.equal(await panel.locator('.header-balloon-title').innerText(), 'Concilium');
  assert.equal(await page.locator('.concilium-seat').count(), 2);
  assert.equal(await page.getByRole('button', { name: /Remove member/ }).count(), 0);
  const add = page.getByRole('button', { name: /Add member/ });
  for (let i = 0; i < 3; i++) await add.click();
  assert.equal(await page.locator('.concilium-seat').count(), 5);
  assert.equal(await add.isDisabled(), true);
  await page.getByTestId('concilium-model-4-trigger').click();
  const search = page.getByTestId('concilium-model-4-search');
  await search.fill('nonexistent model');
  assert.equal(await page.locator('.model-picker-options [role=option]').count(), 0);
  await search.fill('');
  const listed = await page.locator('.model-picker-options [role=option]').allTextContents();
  assert.equal(listed.filter(text => text.includes('gpt-5.4')).length, 0, 'already chosen models cannot be duplicated');
  await search.press('Escape');
  assert.equal(await panel.isVisible(), true, 'Escape closes the nested dropdown first');
  await page.getByRole('button', { name: 'Make chairman', exact: true }).last().click();
  assert.equal(await page.locator('.concilium-seat').last().getByText('Synthesis + skills').count(), 1);
  await page.getByRole('switch', { name: 'Enable Concilium' }).click();
  await page.getByRole('button', { name: 'Remove member 2' }).click();
  assert.equal(await page.locator('.concilium-seat').count(), 4);
  assert.equal(await page.locator('.concilium-seat').last().getByText('Synthesis + skills').count(), 1, 'chairman index follows removal');
  await trigger.click();
  assert.equal(await page.locator('.research-assistant-header select').isDisabled(), true);
  await page.locator('.research-composer-input').fill('Test the selected council.');
  await page.locator('.research-composer-input').press('Enter');
  await page.waitForFunction(() => window.requests.length === 1);
  const request = await page.evaluate(() => window.requests[0]);
  assert.equal(request.concilium.models.length, 4);
  assert.equal(request.concilium.chairman, 3);
  assert.deepEqual(request.model, request.concilium.models[3]);
  await trigger.click();
  await page.getByRole('switch', { name: 'Enable Concilium' }).click();
  await trigger.click();
  await page.locator('.research-composer-input').fill('Ordinary chat again.');
  await page.locator('.research-composer-input').press('Enter');
  await page.waitForFunction(() => window.requests.length === 2);
  assert.equal(await page.evaluate(() => window.requests[1].concilium), undefined);
  await page.setViewportSize({ width: 560, height: 800 });
  await trigger.click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'toolbar fits the compact viewport');
  const box = await panel.boundingBox();
  assert.ok(box.x >= 0 && box.x + box.width <= 560 && box.y >= 0 && box.y + box.height <= 800);
  await panel.getByRole('button', { name: 'Close', exact: true }).click();
  assert.equal(await panel.count(), 0);
  await page.goto('http://127.0.0.1:5198/visual-tests/research-assistant-harness.html?lang=en&view=embedded&theme=dark');
  await trigger.click(); assert.equal(await panel.isVisible(), true);
  assert.deepEqual(errors, []);
  console.log('Concilium UI: header balloon, 2–5 bounds, search, duplicate prevention, nested Escape, chairman/removal, exact request, disable mode, compact and dark layouts passed.');
} finally { await browser.close(); }

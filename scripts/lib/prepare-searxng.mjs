/** Build-time only: stage the pinned SearXNG source and its hash-locked wheels
 * next to the private CPython of the managed runtime. It shares the interpreter,
 * never the dependency folder, so Zotero MCP and SearXNG resolve independently. */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

export const searxngSource = path.resolve(import.meta.dirname, '../../runtime/searxng');

/** Every input that changes the staged bytes, for the runtime fingerprint. */
export function searxngInputs() {
  const files = ['manifest.json', 'requirements.lock', 'settings.yml', 'serve.py', 'license_inventory.py', 'shims/pwd.py'];
  return [import.meta.filename, ...files.map(name => path.join(searxngSource, name))];
}

// Upstream builds file lists with OS-native separators and compares them with
// URL paths, which only matters on Windows. Each replacement must still apply:
// a silently skipped patch would ship a different program than the one tested.
const WINDOWS_PATCHES = [
  ['searx/webutils.py', 'file_list.append(str(f.relative_to(static_path)))', 'file_list.append(f.relative_to(static_path).as_posix())'],
  ['searx/webutils.py', 'f = os.path.join(directory[templates_path_length:], filename)\n', "f = os.path.join(directory[templates_path_length:], filename).replace(os.sep, '/')\n"],
];

export async function stageSearxng({ python, output, cache, archive }) {
  const manifest = JSON.parse(fs.readFileSync(path.join(searxngSource, 'manifest.json'), 'utf8'));
  const target = path.join(output, 'searxng');
  fs.rmSync(target, { recursive: true, force: true });
  fs.mkdirSync(target, { recursive: true });
  const tarball = await archive(manifest.upstreamUrl, manifest.upstreamSha256, `searxng-${manifest.upstreamCommit}.tar.gz`);
  const extracted = path.join(output, 'searxng-upstream');
  fs.rmSync(extracted, { recursive: true, force: true });
  fs.mkdirSync(extracted, { recursive: true });
  execFileSync(python, ['-I', '-c', 'import tarfile,sys; t=tarfile.open(sys.argv[1]); t.extractall(sys.argv[2],filter="data")', tarball, extracted]);
  const upstream = path.join(extracted, fs.readdirSync(extracted)[0]);
  fs.cpSync(path.join(upstream, 'searx'), path.join(target, 'searx'), { recursive: true });
  for (const [file, before, after] of WINDOWS_PATCHES) {
    const location = path.join(target, file);
    const text = fs.readFileSync(location, 'utf8');
    if (!text.includes(before)) throw new Error(`SearXNG patch no longer applies: ${file}`);
    fs.writeFileSync(location, text.replace(before, after));
  }
  const version = `${manifest.upstreamDate.replaceAll('-0', '-').replaceAll('-', '.')}+${manifest.upstreamCommit.slice(0, 9)}`;
  fs.writeFileSync(path.join(target, 'searx/version_frozen.py'), [
    '# SPDX-License-Identifier: AGPL-3.0-or-later',
    '# Generated by Nodus from the pinned upstream archive; no git checkout exists at run time.',
    `VERSION_STRING = "${version}"`, `VERSION_TAG = "${version}"`, `DOCKER_TAG = "${version.replace('+', '-')}"`,
    'GIT_URL = "https://github.com/searxng/searxng"', 'GIT_BRANCH = "master"', ''].join('\n'));
  // AGPL-3.0 section 5(a): the modified work carries a prominent notice.
  fs.writeFileSync(path.join(target, 'searx/NODUS_MODIFICATIONS.txt'), [
    `This copy of SearXNG (${manifest.upstreamUrl}) was modified by Nodus on ${manifest.upstreamDate}.`,
    '- searx/webutils.py: static and template file lists use "/" separators on every platform (Windows).',
    '- searx/version_frozen.py: generated version metadata for a source archive without git.',
    'The unmodified archive is pinned by SHA-256 in runtime/searxng/manifest.json of the Nodus source tree.', ''].join('\n'));
  fs.copyFileSync(path.join(searxngSource, 'serve.py'), path.join(target, 'serve.py'));
  fs.copyFileSync(path.join(searxngSource, 'settings.yml'), path.join(target, 'settings.yml'));
  fs.cpSync(path.join(searxngSource, 'shims'), path.join(target, 'shims'), { recursive: true });
  const dependencies = path.join(target, 'dependencies');
  execFileSync(python, ['-I', '-m', 'pip', '--isolated', '--cache-dir', path.join(cache, 'pip'), 'install', '--disable-pip-version-check', '--only-binary=:all:',
    '--require-hashes', '--no-compile', '--target', dependencies, '-r', path.join(searxngSource, 'requirements.lock')], { cwd: cache, stdio: 'inherit' });
  // Console launchers written by pip point at the build machine's interpreter.
  fs.rmSync(path.join(dependencies, 'bin'), { recursive: true, force: true });
  const legal = path.join(target, 'legal');
  fs.mkdirSync(legal, { recursive: true });
  fs.copyFileSync(path.join(upstream, 'LICENSE'), path.join(legal, 'SEARXNG_LICENSE.txt'));
  fs.copyFileSync(path.join(upstream, 'AUTHORS.rst'), path.join(legal, 'SEARXNG_AUTHORS.rst'));
  fs.copyFileSync(path.join(searxngSource, 'requirements.lock'), path.join(legal, 'requirements.lock'));
  execFileSync(python, ['-I', path.join(searxngSource, 'license_inventory.py'), target, JSON.stringify(manifest)], { stdio: 'inherit' });
  // Precompiled bytecode is read, never written (-B), so the signed runtime stays
  // untouched and a cold start does not pay for compiling a few hundred modules.
  execFileSync(python, ['-I', '-m', 'compileall', '-q', '-j', '0', '--invalidation-mode', 'unchecked-hash', target], { stdio: 'inherit' });
  fs.rmSync(extracted, { recursive: true, force: true });
  return { upstreamCommit: manifest.upstreamCommit, adapterVersion: manifest.adapterVersion, version };
}

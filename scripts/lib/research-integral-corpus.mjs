export async function writeCorpusPdf(directory, document) {
  const pdf = await PDFDocument.create();
  pdf.setTitle(document.title);
  pdf.setAuthor([document.author, document.coauthor].filter(Boolean).map(([first, last]) => `${first} ${last}`).join('; '));
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  for (const lines of document.pages) pdf.addPage([612, 792]).drawText(lines.join('\n'), { x: 50, y: 730, size: 10.5, lineHeight: 17, font, maxWidth: 512 });
  const bytes = await pdf.save();
  fs.mkdirSync(directory, { recursive: true });
  const file = path.join(directory, document.file);
  fs.writeFileSync(file, bytes);
  return { key: document.key, group: document.group, title: document.title, file, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'),
    authors: [document.author, document.coauthor].filter(Boolean).map(([first, last]) => `${first} ${last}`), year: document.year, relation: document.relation,
    quotes: document.pages.map((lines, index) => ({ page: index + 1, quote: lines.find(line => line.startsWith('«')) })) };
}


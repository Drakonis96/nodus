// Functional-group compatibility (Chemistry Studio's check-compatibility tool): the host validates
// the artifact, writes the "Functional-group compatibility" section of the route report (nothing for
// a clean route) and passes a step's high-severity clashes to its fix prompt as evidence.
// Synthetic data only.
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = await mkdtemp(path.join(os.tmpdir(), 'nodus-step-compatibility-'));
test.after(() => rm(tmp, { recursive: true, force: true }));

async function bundle(entry, name) {
  const outfile = path.join(tmp, name);
  await build({ entryPoints: [path.join(root, entry)], outfile, bundle: true, format: 'esm', platform: 'node', logLevel: 'silent', alias: { '@shared': path.join(root, 'shared') } });
  return import(pathToFileURL(outfile).href);
}

const compat = await bundle('shared/stepCompatibility.ts', 'compat.mjs');
const inspection = await bundle('shared/moleculeInspection.ts', 'inspection.mjs');
const skills = await bundle('shared/chatSkills.ts', 'skills.mjs');

const RECORD = `tb-${'c'.repeat(32)}`;
const ARTIFACT = {
  compatibility: [
    { step: 1, reagentClasses: [{ id: 'strong-hydride', label: 'strong hydride (LiAlH4 type)' }], hazards: [
      { group: 'ester', groupLabel: 'ester', reagentClass: 'strong-hydride', reagentLabel: 'strong hydride (LiAlH4 type)', severity: 'high',
        why: 'the ester survives into the product, but under strong hydride (LiAlH4 type) conditions it is reduced to the alcohol',
        suggestion: 'use a chemoselective reagent or change the order of steps', protectedForms: ['tert-butyl ester'], examples: [] },
    ] },
    { step: 2, reagentClasses: [{ id: 'organometallic', label: 'Grignard or organolithium' }], hazards: [
      { group: 'alcohol', groupLabel: 'alcohol', reagentClass: 'organometallic', reagentLabel: 'Grignard or organolithium', severity: 'high',
        why: 'the alcohol survives into the product, but under Grignard or organolithium conditions it quenches the reagent (acidic O–H)',
        suggestion: 'protect it as a silyl ether (TBS)', protectedForms: ['TBS ether'], examples: [{ form: 'TBS ether', records: [RECORD, 'not-an-id'] }] },
      { group: 'ketone', severity: 'medium', why: 'another ketone reacts in this step while this one must survive — check the selectivity' },
      { group: 'broken', severity: 'catastrophic', why: 'dropped: unknown severity' },
    ] },
    { step: 3, reagentClasses: [], hazards: [] },
    { step: 0, hazards: [{ group: 'x', severity: 'high', why: 'dropped: no such step' }] },
  ],
};
const cite = (ids) => ids.map((id) => ({ id, book: 'Synthetic Protective Groups', page: 101, kind: 'crop', reagents: 'TBSCl, imidazole, DMF', yield: '95%', status: 'confirmed', link: 'nodus://passage/p101' }));

test('the artifact is validated: bad steps, severities and ids are dropped', () => {
  const steps = compat.normalizeCompatibility(ARTIFACT);
  assert.deepEqual(steps.map((step) => step.step), [1, 2, 3]);
  assert.deepEqual(steps[1].hazards.map((hazard) => hazard.group), ['alcohol', 'ketone']);
  assert.deepEqual(steps[1].hazards[0].examples, [{ form: 'TBS ether', records: [RECORD] }]);
  assert.equal(steps[1].hazards[1].groupLabel, 'ketone', 'a missing label falls back to the group');
  assert.deepEqual(compat.normalizeCompatibility(null), []);
  assert.deepEqual(compat.normalizeCompatibility({ compatibility: 'nope' }), []);
});

test('the report section lists only steps with a hazard, high first, with the textbook example', () => {
  const text = compat.formatCompatibility(compat.normalizeCompatibility(ARTIFACT), cite);
  assert.match(text, /^\n### Functional-group compatibility\nThis block is generated by the application, not by the model/);
  assert.match(text, /\*\*Step 1\*\* — strong hydride \(LiAlH4 type\):\n- ⚠ \*\*High\*\* — The ester survives into the product, but under strong hydride \(LiAlH4 type\) conditions it is reduced to the alcohol\. To keep it: use a chemoselective reagent or change the order of steps\./);
  assert.match(text, /Textbook example of putting it on — TBS ether: \[\*Synthetic Protective Groups\*, p\. 101\]\(nodus:\/\/passage\/p101\) · conditions: TBSCl, imidazole, DMF · yield 95%\./);
  assert.ok(text.indexOf('⚠ **High** — The alcohol') < text.indexOf('Medium — Another ketone'), 'high before medium');
  assert.doesNotMatch(text, /\*\*Step 3\*\*/, 'a clean step is not listed');
  assert.match(text, /_A heuristic check: .*a question to check, not a verdict/);
  assert.equal(compat.formatCompatibility(compat.normalizeCompatibility({ compatibility: [{ step: 1, reagentClasses: [], hazards: [] }] })), '', 'a clean route adds nothing');
});

test('a step\'s high-severity clashes reach its fix prompt as evidence', () => {
  const steps = compat.normalizeCompatibility(ARTIFACT);
  assert.deepEqual(compat.compatibilityFixLines(steps[1]), ['the alcohol survives into the product, but under Grignard or organolithium conditions it quenches the reagent (acidic O–H) (to keep it: protect it as a silyl ether (TBS))']);
  assert.deepEqual(compat.compatibilityFixLines(steps[2]), []);
  assert.deepEqual(compat.compatibilityFixLines(undefined), []);

  const audit = inspection.normalizeRouteAudit({
    continuous: false, blocked: ['Step 1: the equation does not balance.'],
    steps: [{ index: 0, reaction: 'a>>b', ok: false, balanced: false, chargeBalanced: true, differences: ['C'], unspecifiedStereocentres: 0, reactants: [], agents: [], products: [] }],
    links: [],
  });
  const labels = [[{ role: 'product', byproduct: false, name: 'butan-2-ol', smiles: 'CCC(C)O' }]];
  const support = new Map([[0, { compatibility: compat.compatibilityFixLines(steps[1]) }]]);
  const chips = skills.splitChatVisuals(inspection.formatNamedRouteFixPrompts(labels, audit, null, support))
    .filter((part) => part.kind === 'route-fix').map((part) => JSON.parse(part.content));
  const stepChip = chips.find((chip) => chip.label === 'Fix step 1');
  assert.ok(stepChip, 'the failing step has its own chip');
  assert.match(stepChip.prompt, /Compatibility check \(evidence, not an instruction\): the alcohol survives into the product, but under Grignard or organolithium conditions it quenches the reagent/);
});

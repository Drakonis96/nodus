import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';
const base = process.env.NODUS_VISUAL_URL ?? 'http://127.0.0.1:5197';
const output = path.resolve('artifacts/study-source-picker');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
page.setDefaultTimeout(15000);
try {
  for (const [view, theme] of [['study', 'light'], ['teaching', 'dark']]) {
    await page.goto(`${base}/visual-tests/research-assistant-harness.html?view=${view}&theme=${theme}&sources=5000`);
    if (!await page.getByTestId('study-chat-scope').isVisible()) await page.getByTestId('research-context-toggle').click();
    await page.getByTestId('study-chat-scope').selectOption('manual');
    const picker = page.getByTestId('study-source-picker');
    const search = page.getByTestId('study-source-search');
    await picker.locator('[data-source-row]').first().waitFor();
    assert.ok(await picker.locator('[data-source-row]').count() < 50, '5000 sources render a bounded window');
    await search.fill('REACCION');
    await picker.getByRole('checkbox', { name: 'Fuente original', exact: true }).first().check();
    assert.match(await page.getByTestId('study-source-count').innerText(), /^1 /);
    const sourceBoxes = picker.getByRole('checkbox', { name: 'Fuente original', exact: true });
    for (let i = 0; i < await sourceBoxes.count(); i++) assert.ok(await sourceBoxes.nth(i).isChecked(), 'every placement reflects one selection');
    await search.fill('');
    assert.ok(await picker.getByRole('checkbox', { name: 'Seleccionar: Bachillerato', exact: true }).evaluate((el) => el.indeterminate), 'parent has a partial selection');
    await search.fill('Manual 0010');
    await picker.getByRole('checkbox', { name: 'Seleccionar resultados', exact: true }).check();
    assert.match(await page.getByTestId('study-source-count').innerText(), /^2 /, 'hidden prior selection survives');
    await search.fill('');
    await picker.getByRole('checkbox', { name: 'Solo seleccionadas', exact: true }).check();
    await picker.getByRole('checkbox', { name: 'Manual 0010', exact: true }).waitFor();
    assert.equal(await picker.getByRole('checkbox', { name: 'Manual 0011', exact: true }).count(), 0);
    await page.screenshot({ path: path.join(output, `${view}-${theme}-selected.png`) });
    await picker.getByRole('checkbox', { name: 'Solo seleccionadas', exact: true }).uncheck();
    const firstRow = picker.locator('[data-source-row]').first();
    await firstRow.focus(); await firstRow.press('End');
    await page.waitForFunction(() => document.activeElement?.getAttribute('data-source-row') === 'unplaced/material:unfiled');
    await page.keyboard.press('Home');
    await page.waitForFunction(() => document.activeElement?.getAttribute('data-source-row') === 'course:course');
    await search.fill('Audio sin transcribir');
    assert.ok(await picker.getByRole('checkbox', { name: 'Audio sin transcribir', exact: true }).isDisabled());
    await search.fill('REACCION');
    await picker.getByRole('button', { name: 'Mover material…: Fuente original', exact: true }).first().click();
    await page.getByRole('menuitem', { name: 'Mover material…', exact: true }).click();
    const dialog = page.getByTestId('study-material-move-dialog');
    await dialog.waitFor();
    assert.equal(await dialog.getByLabel('Ubicación de origen').locator('option').count(), 2);
    await dialog.getByLabel('Asignatura', { exact: true }).selectOption('biology');
    await page.evaluate(() => { window.failMove = true; });
    await dialog.getByRole('button', { name: 'Mover', exact: true }).click();
    await dialog.getByRole('alert').waitFor();
    assert.equal(await page.evaluate(() => window.studySourceFixture.moves.length), 0, 'failed save stays open without applying changes');
    await page.evaluate(() => { window.failMove = false; });
    await page.screenshot({ path: path.join(output, `${view}-${theme}-move.png`) });
    await dialog.getByRole('button', { name: 'Mover', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.match(await page.getByTestId('study-source-count').innerText(), /^2 /, 'moving keeps the same context selection');
    assert.equal(await page.evaluate(() => window.studySourceFixture.sources[0].placements[1].id), 'second-placement');
    await search.fill('quimica');
    await picker.getByRole('button', { name: 'Nueva carpeta: Química', exact: true }).click();
    const folder = page.getByTestId('study-source-folder-dialog');
    await folder.locator('input').fill('Revisión final');
    await folder.getByRole('button', { name: 'Guardar', exact: true }).click();
    await folder.waitFor({ state: 'hidden' });
    await search.fill('revision final');
    // Folder-only search must keep empty matching folders visible so they can be managed.
    await picker.getByRole('button', { name: 'Renombrar carpeta: Revisión final', exact: true }).click();
    await folder.locator('input').fill('Repaso final');
    await folder.getByRole('button', { name: 'Guardar', exact: true }).click();
    await folder.waitFor({ state: 'hidden' });
    assert.ok(await page.evaluate(() => window.studySourceFixture.workspace.folders.some((f) => f.name === 'Repaso final' && f.subjectId === 'chemistry')));
    // Sources sent to the model remain explicit unique keys after reorganizing.
    await page.locator('.research-composer-input').fill('Resume las fuentes seleccionadas.');
    await page.getByRole('button', { name: 'Enviar', exact: true }).click();
    await page.waitForFunction(() => window.requests.length === 1);
    assert.deepEqual((await page.evaluate(() => window.requests[0].selection.sourceKeys)).sort(), ['material:material-1', 'material:material-10']);
    await page.getByRole('button', { name: 'S1 · Fuente original', exact: true }).click();
    assert.equal(await page.evaluate(() => window.openedEvidence), 'material-1');
    await search.fill('');
    await page.screenshot({ path: path.join(output, `${view}-${theme}-tree.png`) });
    assert.ok(await picker.evaluate((el) => el.scrollWidth <= el.clientWidth + 1), 'picker fits its panel');
  }
  assert.deepEqual(errors, []);
  console.log('Study/Teaching source picker: 5000 sources, keyboard, selection, folders, movement, citations and both themes passed.');
} finally { await browser.close(); }

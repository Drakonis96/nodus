/**
 * Nodus Drift: the local catalogue. Recordings first, then the generators.
 *
 * The recordings' identifiers, English labels and relative paths were read from the
 * active catalogue of Moodist (src/data/sounds/*) at the pinned commit below. Their
 * technical fields (bytes, SHA-256, duration, crossfade) are MEASURED from the files
 * at that commit, never typed by hand: `node scripts/prepare-drift-assets.mjs --measure <dir>`
 * reproduces them. No Moodist source code is used. Moodist's own noise and binaural
 * WAV files, and its alarm and silence helpers, are deliberately not part of this
 * catalogue: the generators below are implemented locally.
 *
 * Licences are NOT presumed. Moodist declares its audio as third-party material under
 * either the Pixabay Content License or CC0 without saying which applies to each file, so
 * every recording is `unresolved` and `pending` review until legal/drift/REVIEW.md records
 * evidence for it. An unresolved recording is listed but is never bundled, read or played.
 *
 * `crossfadeMs` rule (see legal/drift/PROVENANCE.md): 0 keeps a loop that is already
 * seamless (seam step <= 4x the median sample step and the last and first 100 ms within
 * 6 dB of each other); otherwise a circular crossfade of min(1000 ms, 20% of the duration).
 */
import type { DriftCategoryId, DriftSoundDefinition } from './drift';
import { BINAURAL_CARRIER_HZ } from './drift';

export const DRIFT_UPSTREAM = {
  repository: 'https://github.com/remvze/moodist',
  commit: '11c0be2200116a3635880d600fd6953899cc51a3',
  /** The licence of Moodist's CODE. Its audio is third-party and is tracked per file. */
  codeLicense: 'MIT',
} as const;

const UNRESOLVED_EVIDENCE = ['legal/drift/PROVENANCE.md#upstream-declaration'];

interface Described {
  id: string;
  categoryId: DriftCategoryId;
  icon: string;
  nameKey: string;
  descriptionKey: string;
}

function recording(
  described: Described,
  file: { asset: string; bytes: number; sha256: string; durationSeconds: number; crossfadeMs: number },
): DriftSoundDefinition {
  return {
    ...described,
    source: { kind: 'file', ...file, loop: true },
    provenance: {
      licenseStatus: 'unresolved',
      upstreamRepository: DRIFT_UPSTREAM.repository,
      upstreamCommit: DRIFT_UPSTREAM.commit,
      upstreamPath: `public/sounds/${file.asset}`,
      evidenceRefs: [...UNRESOLVED_EVIDENCE],
      distributionReview: 'pending',
    },
  };
}

/** Generated by Nodus code, so there is no third-party right to review (legal/drift/REVIEW.md). */
const FIRST_PARTY_GENERATOR = {
  licenseStatus: 'verified',
  licenseId: 'AGPL-3.0-only',
  evidenceRefs: ['legal/drift/REVIEW.md#first-party-generators'],
  distributionReview: 'approved',
  reviewRef: 'legal/drift/REVIEW.md#first-party-generators',
} as const;

function noise(described: Omit<Described, 'categoryId' | 'icon'>, color: 'white' | 'pink' | 'brown'): DriftSoundDefinition {
  return {
    ...described,
    categoryId: 'noise',
    icon: 'waveform',
    source: { kind: 'noise', color },
    provenance: { ...FIRST_PARTY_GENERATOR, evidenceRefs: [...FIRST_PARTY_GENERATOR.evidenceRefs] },
  };
}

function binaural(described: Omit<Described, 'categoryId' | 'icon'>, beatHz: number): DriftSoundDefinition {
  return {
    ...described,
    categoryId: 'binaural',
    icon: 'sine',
    source: { kind: 'binaural', carrierHz: BINAURAL_CARRIER_HZ, beatHz },
    provenance: { ...FIRST_PARTY_GENERATOR, evidenceRefs: [...FIRST_PARTY_GENERATOR.evidenceRefs] },
  };
}

